# -*- coding: utf-8 -*-
"""按显示宽度（east_asian_width W/F 计 2）排布 HUD 分区 ASCII 示意图，避免中文错位。

2026-09-24 三次改版：物品格与贴图整体缩小（快捷栏 64→52、背包/箱子 44→36），
左列三块面板跟着收窄上移（背包 y10~192 / 箱子 y200~362 / 制作栏 y370~626）。
生成结果直接贴进 大纲.md 6.1。
"""
import unicodedata


def dw(s: str) -> int:
    return sum(2 if unicodedata.east_asian_width(c) in ("W", "F") else 1 for c in s)


def pad(s: str, w: int) -> str:
    return s + " " * max(0, w - dw(s))


W = "│"
A, B, C, D = 22, 8, 12, 18   # 四列内容宽度（显示宽度）：左列 / 中列 / 小地图列 / 按钮+状态列

rows = [
    ("  背包", "", "  小地图", "  暂停按钮"),
    ("  背包", "", "  小地图", "  大地图"),
    ("  背包", "", "  小地图", "  小地图开关"),
    ("  背包", "", "  小地图", "  状态栏"),
    ("  箱子", "", "  小地图", "  状态栏"),
    ("  箱子", "", "  时间", ""),
    ("  箱子", "", "", "  装备栏"),
    ("  箱子", "", "", "  装备栏"),
    ("  制作栏", "", "", "  装备栏"),
    ("  制作栏", "", "", "  装备栏"),
    ("  制作栏", "  短提示", "", "  装备栏"),
    ("  制作栏", "", "", "  装备栏"),
    ("  制作栏", "", "", "  装备栏"),
    ("  物品栏", "", "", "  装备栏"),
]

out = []
out.append("┌" + "─" * A + "┬" + "─" * B + "┬" + "─" * C + "┬" + "─" * D + "┐")
for a, b, c, d in rows:
    out.append(W + pad(a, A) + W + pad(b, B) + W + pad(c, C) + W + pad(d, D) + W)
out.append("└" + "─" * A + "┴" + "─" * B + "┴" + "─" * C + "┴" + "─" * D + "┘")

print("\n".join(out))
